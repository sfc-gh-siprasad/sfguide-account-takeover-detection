"""Where the app gets its data: bundled CSVs (sample mode) or Snowflake (live mode).

Live mode: SNOWFLAKE_CONNECTION_NAME=<connection> streamlit run app/streamlit_app.py
In Streamlit in Snowflake, the active Snowpark session is used automatically.
"""

import os
from pathlib import Path

import pandas as pd

DATA = Path(__file__).resolve().parents[1] / "data"
DB, SCHEMA = "ACCOUNT_TAKEOVER", "DATA"
ROLE, WAREHOUSE = "ATO_DEMO_ROLE", "ATO_DEMO_WH"
TABLES = ("customers", "identity_events", "account_changes", "transactions")

_CONN = None


class LiveUnavailable(Exception):
    pass


def sample_frames() -> dict:
    return {n: pd.read_csv(DATA / f"{n}.csv", keep_default_na=False, na_values=[""]) for n in TABLES}


def _query(sql: str) -> pd.DataFrame:
    global _CONN
    try:
        from snowflake.snowpark.context import get_active_session
        df = get_active_session().sql(sql).to_pandas()
    except Exception:
        if _CONN is None or _CONN.is_closed():
            try:
                import snowflake.connector
            except ImportError as exc:
                raise LiveUnavailable("Install snowflake-connector-python to use live mode.") from exc
            name = os.environ.get("SNOWFLAKE_CONNECTION_NAME")
            if not name:
                raise LiveUnavailable("Set SNOWFLAKE_CONNECTION_NAME to a connection in your Snowflake config.")
            try:
                _CONN = snowflake.connector.connect(connection_name=name, role=ROLE, warehouse=WAREHOUSE,
                                                    database=DB, schema=SCHEMA,
                                                    enable_server_session_keep_alive_auto_detection=False)
            except Exception as exc:
                raise LiveUnavailable(f"Could not connect with '{name}': {exc}") from exc
        cur = _CONN.cursor()
        try:
            cur.execute(sql)
            df = cur.fetch_pandas_all()
        finally:
            cur.close()
    df.columns = [c.lower() for c in df.columns]
    return df


def live_frames() -> dict:
    return {n: _query(f"SELECT * FROM {DB}.{SCHEMA}.{n}") for n in TABLES}


RULE_VIEWS = {
    "takeover_sequence": "RULE_TAKEOVER_SEQUENCE", "impossible_travel": "RULE_IMPOSSIBLE_TRAVEL",
    "new_device_country": "RULE_NEW_DEVICE_COUNTRY", "mfa_fatigue": "RULE_MFA_FATIGUE",
    "credential_stuffing": "RULE_CREDENTIAL_STUFFING", "unusual_amount": "RULE_UNUSUAL_AMOUNT",
}


def live_rule_hits() -> dict:
    """Per-rule hits and evidence from the SQL rule views (sql/03_detection_rules.sql): {rule: {customer_id: why}}."""
    union = " UNION ALL ".join(
        f"SELECT '{rule}' AS rule_name, customer_id, why FROM {DB}.{SCHEMA}.{view}" for rule, view in RULE_VIEWS.items())
    hits = {rule: {} for rule in RULE_VIEWS}
    for r in _query(union).itertuples(index=False):
        hits[r.rule_name][r.customer_id] = r.why
    return hits


def live_summaries() -> pd.DataFrame:
    """Case summaries generated by Cortex AI_COMPLETE for the top alerts."""
    return _query(f"SELECT customer_id, case_summary FROM {DB}.{SCHEMA}.CASE_SUMMARIES")
